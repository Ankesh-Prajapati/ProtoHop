// Generates assets/palette.css: the original stylesheet's blue-tinted colour tokens, desaturated
// toward charcoal/slate. Other hues (green, amber, violet, teal packet colours) are kept as they are.
//   node tools/build_palette.js
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const css = fs.readFileSync(path.join(root, 'assets/index-C1vckX_Q.css'), 'utf8')

const block = sel => {
  const i = css.indexOf(sel + '{')
  return css.slice(i + sel.length + 1, css.indexOf('}', i))
}

// share of the original saturation kept, per token kind and theme
const KEEP = {
  light: { fill: 0.45, line: 0.4, text: 0.5, accent: 0.85, other: 0.45 },
  dark: { fill: 0.32, line: 0.3, text: 0.18, accent: 0.8, other: 0.32 }
}

function hexToHsl(hex) {
  const n = hex.length === 4 ? hex.slice(1).split('').map(c => c + c).join('') : hex.slice(1, 7)
  const [r, g, b] = [0, 2, 4].map(i => parseInt(n.slice(i, i + 2), 16) / 255)
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2
  if (max === min) return [0, 0, l]
  const d = max - min
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min)
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4
  return [h * 60, s, l]
}

function hslToHex(h, s, l) {
  const f = n => {
    const k = (n + h / 30) % 12
    const c = l - s * Math.min(l, 1 - l) * Math.max(-1, Math.min(k - 3, 9 - k, 1))
    return Math.round(c * 255).toString(16).padStart(2, '0')
  }
  return `#${f(0)}${f(8)}${f(4)}`
}

function remap(theme, src) {
  const out = []
  for (const [, name, value] of src.matchAll(/(--k-[a-z0-9-]+):\s*(#[0-9a-fA-F]{3,8})/g)) {
    const [h, s, l] = hexToHsl(value.toLowerCase())
    if (h < 195 || h > 250 || s < 0.08) continue
    const kind = (name.match(/^--k-(fill|line|text|accent)-/) || [, 'other'])[1]
    const alpha = value.length === 9 ? value.slice(7) : ''
    out.push(`${name}:${hslToHex(h, s * KEEP[theme][kind], l)}${alpha}`)
  }
  return out
}

const light = remap('light', block(':root'))
const dark = remap('dark', block('[data-theme=dark]'))
const banner = '/* generated by tools/build_palette.js: blue-tinted tokens of the original theme, toned down */\n'
fs.writeFileSync(path.join(root, 'assets/palette.css'),
  `${banner}:root{${light.join(';')}}\n[data-theme=dark]{${dark.join(';')}}\n`)
console.log(`palette.css: ${light.length} light and ${dark.length} dark tokens remapped`)
